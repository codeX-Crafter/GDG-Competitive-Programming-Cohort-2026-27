#include <iostream>
using namespace std;

int main(){
    int a = 4, b = 7;
    cout << (a < b) << endl;        // true
    cout << (a > b) << endl;        // false
    cout << (a <= b) << endl;       // true
    cout << (a >= b) << endl;       // false
    cout << (a == b) << endl;       // false
    cout << (a != b) << endl;       // true
    return 0;
}